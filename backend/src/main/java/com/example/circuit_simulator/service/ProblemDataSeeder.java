    @Override
    @Transactional
    public void run(String... args) {
        removeRetiredChapters();
        removeRetiredProblems();
        seedChapter("ST", ST_PROBLEMS);
        seedChapter("LR", LR_PROBLEMS);
        seedChapter("SW", SW_PROBLEMS);
        seedChapter("DM", DM_PROBLEMS);
        seedChapter("VR", VR_PROBLEMS);
        seedChapter("CP", CP_PROBLEMS);
        seedChapter("DI", DI_PROBLEMS);
        seedChapter("TR", TR_PROBLEMS);
        seedChapter("TCP", TCP_PROBLEMS);
        seedChapter("PR", PR_PROBLEMS);
    }

    /** Remove legacy modules that should no longer appear or remain directly addressable. */
    private void removeRetiredChapters() {
        for (String code : List.of("TRL")) {
            chapterRepository.findByCode(code).ifPresent(chapter -> {
                for (Problem problem : problemRepository.findAllByChapterCode(code)) {
                    circuitRepository.findByProblemId(problem.getId())
                            .forEach(circuitRepository::delete);
                    problemRepository.delete(problem);
                }
                chapterRepository.delete(chapter);
                System.out.println("Removed retired " + code + " chapter.");
            });
        }
    }

    /** Drop problems that were seeded by mistake and should no longer appear. */
    private void removeRetiredProblems() {
        for (String code : List.of("SW.L3.12")) {
            problemRepository.findByCode(code).ifPresent(problem -> {
                circuitRepository.findByProblemId(problem.getId())
                        .forEach(circuitRepository::delete);
                problemRepository.delete(problem);
                System.out.println("Removed retired problem " + code + ".");
            });
        }
    }

    private void seedChapter(String chapterCode, List<ProblemSeed> seeds) {
        chapterRepository.findByCode(chapterCode).ifPresentOrElse(
                chapter -> {
                    for (ProblemSeed seed : seeds) {
                        problemRepository.findByCode(seed.code()).ifPresentOrElse(
                                problem -> updateProblem(problem, chapter, seed),
                                () -> createProblem(chapter, seed)
                        );
                    }
                    System.out.println(chapterCode + " chapter problems seeded (" + seeds.size() + ").");
                },
                () -> System.err.println(
                        "ProblemDataSeeder: chapter " + chapterCode + " not found — skipping problem seed")
        );
    }

    private void createProblem(Chapter chapter, ProblemSeed seed) {
        Problem problem = new Problem();
        problem.setCode(seed.code());
        problem.setTitle(seed.title());
        problem.setDisplayOrder(seed.displayOrder());
        problem.setChapter(chapter);
        problem.setDifficulty("beginner");
        applyRichContent(problem, seed.code());
        problemRepository.save(problem);
    }

    private void updateProblem(Problem problem, Chapter chapter, ProblemSeed seed) {
        problem.setTitle(seed.title());
        problem.setDisplayOrder(seed.displayOrder());
        problem.setChapter(chapter);
        applyRichContent(problem, seed.code());
        problemRepository.save(problem);
    }

